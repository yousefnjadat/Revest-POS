package com.example.pos.ui.theme

import androidx.compose.ui.unit.dp

/** Spacing steps in multiples of 8dp, plus the few shared shape and target sizes. */
object PosSpacing {
    val xs = 4.dp
    val sm = 8.dp
    val md = 16.dp
    val lg = 24.dp
    val xl = 32.dp

    /** Horizontal padding every screen uses, so content lines up across destinations. */
    val screenHorizontal = 16.dp

    /** Smallest comfortable tap target. */
    val touchTarget = 48.dp
}
